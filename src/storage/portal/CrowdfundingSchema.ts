import { Static, Type } from "typebox";
import type { ITabularStorage } from "workglow";
import { createServiceToken } from "workglow";
import { TypeNullable } from "../../util/TypeBoxUtil";
import { TypeSecCik } from "../../util/TypeSecCik";

/**
 * Crowdfunding schema - represents crowdfunding entities
 */
export const CrowdfundingSchema = Type.Object({
  cik: TypeSecCik({ description: "Central Index Key (CIK) - unique identifier for entity" }),
  file_number: Type.String({
    maxLength: 32,
    description: "File number",
  }),
  filing_date: Type.String({
    format: "date",
    description: "Filing date",
  }),
  name: Type.String({
    maxLength: 140,
    description: "Entity name",
  }),
  legal_status: Type.String({
    maxLength: 50,
    description: "Legal status",
  }),
  state_jurisdiction: Type.String({
    maxLength: 2,
    description: "State jurisdiction code",
  }),
  date_incorporation: Type.String({
    format: "date",
    description: "Date of incorporation",
  }),
  url: Type.String({
    maxLength: 256,
    description: "Issuer website",
  }),
  portal_cik: TypeSecCik({ description: "Portal CIK" }),
  status: Type.String({
    maxLength: 32,
    description: "Offering lifecycle status (generated by determineStatus)",
  }),
  progress_update: TypeNullable(
    Type.String({
      maxLength: 256,
      description: "Latest C-U progress-update narrative",
    })
  ),
  nature_of_amendment: TypeNullable(
    Type.String({
      maxLength: 256,
      description: "Latest C/A nature-of-amendment narrative",
    })
  ),
});

export type Crowdfunding = Static<typeof CrowdfundingSchema>;

/**
 * Crowdfunding repository storage type and primary key definitions
 */
export const CrowdfundingPrimaryKeyNames = ["cik", "file_number"] as const;
export type CrowdfundingRepositoryStorage = ITabularStorage<
  typeof CrowdfundingSchema,
  typeof CrowdfundingPrimaryKeyNames,
  Crowdfunding
>;

/**
 * Dependency injection tokens for repositories
 */
export const CROWDFUNDING_REPOSITORY_TOKEN = createServiceToken<CrowdfundingRepositoryStorage>(
  "sec.storage.crowdfundingRepository"
);

