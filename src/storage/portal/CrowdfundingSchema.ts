/**
 * Crowdfunding Reports schema - represents crowdfunding reports
 */
export const CrowdfundingReportsSchema = Type.Object({
  cik: TypeSecCik({ description: "Central Index Key (CIK) - unique identifier for entity" }),
  file_number: Type.String({
    maxLength: 32,
    description: "File number",
  }),
  filing_date: Type.String({
    format: "date",
    description: "Filing date",
  }),
  disclosure_name: Type.String({
    maxLength: 50,
    description: "Disclosure name",
  }),
  disclosure_value: TypeNullable(
    Type.Number({
      // Deliberately unbounded below. Four of the eighteen Reg CF disclosures
      // are routinely negative — netIncome/taxPaid for both fiscal years — and
      // a Reg CF issuer is an early-stage company, so a loss is the common case
      // rather than the exception.
      //
      // A `minimum: 0` here emitted a CHECK constraint whose failure mode was a
      // PARTIAL write, not a clean rejection: the parent `crowdfunding` row
      // committed and looked healthy while the disclosure insert aborted at the
      // first negative value, dropping that field and every one after it. FAFCO
      // stored 15 of 18 disclosures that way, missing exactly the four above.
      //
      // rega_financial_data is the same name/value financial-disclosure table
      // for Reg A and has never carried such a bound.
      description: "Disclosure value (may be negative — e.g. net income, tax paid)",
    })
  ),
});

export type CrowdfundingReports = Static<typeof CrowdfundingReportsSchema>;

/**
 * Crowdfunding Reports repository storage type and primary key definitions
 */
export const CrowdfundingReportsPrimaryKeyNames = [
  "cik",
  "file_number",
  "filing_date",
  "disclosure_name",
] as const;
export type CrowdfundingReportsRepositoryStorage = ITabularStorage<
  typeof CrowdfundingReportsSchema,
  typeof CrowdfundingReportsPrimaryKeyNames,
  CrowdfundingReports
>;

export const CROWDFUNDING_REPORTS_REPOSITORY_TOKEN =
  createServiceToken<CrowdfundingReportsRepositoryStorage>(
    "sec.storage.crowdfundingReportsRepository"
  );
